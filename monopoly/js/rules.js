// Полные правила игры (показываются в окне «Правила»).
import { BOARD, GROUPS, BONUS, groupCells } from './data.js';

const k = (n) => `${n} 000 ₽`;

export function rulesHTML() {
  const groups = Object.entries(GROUPS).map(([g, d]) => {
    const names = groupCells(g).map((i) => BOARD[i].name).join(', ');
    return `<tr><td><span style="display:inline-block;width:10px;height:10px;border-radius:3px;background:${d.color}"></span> ${d.name}</td><td>${names}</td><td>${k(d.house)}</td></tr>`;
  }).join('');
  const bonus = Object.values(BONUS).map((b) => `<li><b>${b.emoji} ${b.name}</b> (${b.when.toLowerCase()}) — ${b.text}${b.kind === 'mean' ? ' <i>Подлянка.</i>' : ''}</li>`).join('');
  return `
  <div class="rules">
    <p><b>Цель игры:</b> разорить соперника или, если включено ограничение по кругам, оказаться богаче к концу игры. Богатство = деньги + стоимость объектов (заложенные — за полцены) + стоимость построек.</p>

    <h4>🎲 Ход</h4>
    <ul>
      <li>Бросаешь два кубика и идёшь на выпавшее число клеток по часовой стрелке.</li>
      <li><b>Дубль</b> (одинаковые значения) — после хода бросаешь ещё раз. <b>Три дубля подряд</b> — сразу в обезьянник.</li>
      <li>Проходя или вставая на <b>Старт</b>, получаешь зарплату (обычно ${k(200)}).</li>
      <li>Пока ход твой, можно строить дома, закладывать объекты, играть бонусные карты и предлагать обмен. Ход заканчивается кнопкой «Завершить ход».</li>
    </ul>

    <h4>🏪 Покупка и аренда</h4>
    <ul>
      <li>Встав на свободный объект, можно купить его по цене банка. Если отказываешься — объект уходит с <b>аукциона</b>: игроки по очереди повышают ставку (минимум ${k(10)}), пас — значит, побеждает другой. Свою ставку можно делать, даже если ты отказался от покупки.</li>
      <li>Встав на чужой объект, платишь владельцу аренду. С заложенных объектов и объектов, закрытых проверкой 🔍, аренда не берётся.</li>
      <li><b>Монополия</b> — все объекты одного цвета у одного игрока. Аренда на пустых участках монополии удваивается, и только в монополии можно строить.</li>
      <li><b>Транспорт</b> (Аэроэкспресс, Ласточка, Сапсан, Метро): аренда ${k(25)} / ${k(50)} / ${k(100)} / ${k(200)} при 1–4 компаниях у владельца.</li>
      <li><b>Сервисы</b> (Яндекс Go, Whoosh): аренда = сумма кубиков × 4, а если у владельца оба — × 10.</li>
    </ul>

    <h4>🏠 Строительство</h4>
    <ul>
      <li>Строить можно только в свой ход, на монополии без заложенных участков.</li>
      <li>Строй <b>равномерно</b>: нельзя ставить второй дом на участок, пока на другом участке группы нет первого. Продавать — тоже равномерно.</li>
      <li>После 4 домов можно построить <b>отель</b> (5-й уровень). В банке всего 32 дома и 12 отелей.</li>
      <li>Постройки продаются банку за полцены в любой момент.</li>
    </ul>
    <table><tr><th>Группа</th><th>Объекты</th><th>Дом</th></tr>${groups}</table>

    <h4>🏦 Залог</h4>
    <ul>
      <li>Объект без построек в группе можно заложить в любой момент и получить половину его цены.</li>
      <li>Выкуп из залога стоит половину цены + 10%.</li>
      <li>Если получаешь заложенный объект при обмене, платишь банку 10% от залоговой стоимости.</li>
    </ul>

    <h4>🚔 Обезьянник</h4>
    <ul>
      <li>Сюда попадают с клетки «Задержание», по карточке или за три дубля подряд. Если просто встал на клетку — ты в гостях.</li>
      <li>Выйти можно: заплатив штраф ${k(50)} до броска, сыграв карту «Хороший адвокат» или выбросив дубль (до 3 попыток). После третьей неудачной попытки платишь штраф и идёшь.</li>
      <li>Сидя в обезьяннике, ты продолжаешь получать аренду.</li>
    </ul>

    <h4>🃏 Карточки «Шанс» и «Копилка»</h4>
    <ul>
      <li><b>Шанс</b> — непредсказуемые события: переезды, штрафы, выигрыши и подлянки.</li>
      <li><b>Копилка</b> — в основном приятности: премии, наследство, подарки. Есть и «живые» карты: сделай что-то милое в реальной жизни — получи деньги.</li>
      <li>Некоторые карты дают <b>бонусную карту</b>, которая остаётся на руке:</li>
    </ul>
    <ul>${bonus}</ul>

    <h4>📜 Сюжет и главы</h4>
    <ul>
      <li>Игра идёт главами (по умолчанию 4 круга). Каждая глава — событие в жизни Москвы, которое меняет правила: распродажи, туристический сезон, налоговые проверки, Новый год, День святого Валентина и другие.</li>
      <li>В каждой главе есть <b>задание</b>. Кто первым выполнит его — получает награду.</li>
      <li>Если игра ограничена по кругам, последние 3 круга — «Финал: битва магнатов» с повышенной арендой.</li>
    </ul>

    <h4>🤝 Обмен</h4>
    <ul>
      <li>В любой момент можно предложить сопернику обмен: объекты, деньги и бонусные карты в любой комбинации. Объекты из групп с постройками обменивать нельзя — сначала продай постройки.</li>
    </ul>

    <h4>💔 Долги и банкротство</h4>
    <ul>
      <li>Если денег не хватает на обязательный платёж, баланс уходит в минус. Пока он отрицательный, нельзя бросать кубики и завершать ход — продавай постройки и закладывай объекты.</li>
      <li>Если расплатиться невозможно — объявляй банкротство. Соперник побеждает.</li>
    </ul>

    <h4>⚙️ Дополнительные правила (настраиваются в комнате)</h4>
    <ul>
      <li><b>Аукционы</b> — при отказе от покупки объект разыгрывается.</li>
      <li><b>Джекпот</b> — налоги и штрафы копятся в Парке Горького, и их забирает тот, кто туда встанет.</li>
      <li><b>Двойной Старт</b> — точное попадание на Старт даёт двойную зарплату.</li>
      <li><b>Ограничение по кругам</b> — в конце побеждает самый богатый.</li>
    </ul>

    <h4>📱 Как играть с двух устройств</h4>
    <ul>
      <li>Один игрок создаёт комнату и видит код из 4 символов и QR-код.</li>
      <li>Второй открывает эту же страницу, вводит код (или сканирует QR) и попадает в комнату.</li>
      <li>Связь идёт напрямую между устройствами. Если соединение оборвётся — просто обновите страницу, игра сохраняется у создателя комнаты.</li>
    </ul>
  </div>`;
}
